
USE GEOPULSE_DB;

-- Create the zone footfall summary table
CREATE TABLE IF NOT EXISTS ZONE_FOOTFALL (
    ZONE_ID VARCHAR(50),
    ZONE_NAME VARCHAR(100),
    TOTAL_GPS_PINGS BIGINT,
    UNIQUE_DEVICES BIGINT
);

-- Recalculate zone-wise footfall
TRUNCATE TABLE ZONE_FOOTFALL;

INSERT INTO ZONE_FOOTFALL
    (ZONE_ID, ZONE_NAME, TOTAL_GPS_PINGS, UNIQUE_DEVICES)
SELECT
    z.ZONE_ID,
    z.ZONE_NAME,
    COUNT(g.DEVICE_ID) AS TOTAL_GPS_PINGS,
    COUNT(DISTINCT g.DEVICE_ID) AS UNIQUE_DEVICES
FROM ZONES z
LEFT JOIN GPS_PINGS g
    ON g.LATITUDE BETWEEN z.MIN_LAT AND z.MAX_LAT
   AND g.LONGITUDE BETWEEN z.MIN_LON AND z.MAX_LON
GROUP BY z.ZONE_ID, z.ZONE_NAME;

-- View the results
SELECT
    ZONE_NAME,
    TOTAL_GPS_PINGS,
    UNIQUE_DEVICES
FROM ZONE_FOOTFALL
ORDER BY TOTAL_GPS_PINGS DESC;